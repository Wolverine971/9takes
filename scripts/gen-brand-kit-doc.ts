// scripts/gen-brand-kit-doc.ts
// Writes docs/brand/brand-assets.md from src/lib/brand/ (the same data /admin/brand renders), so
// agents can read the brand kit without logging in. Run after editing anything in src/lib/brand/:
//   pnpm gen:brand-kit
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import * as kit from '../src/lib/brand/brandKit';
import { BRAND_CARD_PRESETS, ogImageUrl } from '../src/lib/brand/brandCardPresets';
import { CARD_FORMATS } from '../src/lib/brand/brandTokens';

const OUT = path.resolve('docs/brand/brand-assets.md');

const table = (head: string[], rows: string[][]): string =>
	[
		`| ${head.join(' | ')} |`,
		`| ${head.map(() => '---').join(' | ')} |`,
		...rows.map(
			(r) => `| ${r.map((c) => c.replace(/\|/g, '\\|').replace(/\n/g, '<br>')).join(' | ')} |`
		)
	].join('\n');

const bullets = (items: readonly string[]): string => items.map((i) => `- ${i}`).join('\n');

const doc = `<!-- docs/brand/brand-assets.md -->
<!-- GENERATED by \`pnpm gen:brand-kit\` from src/lib/brand/. Do not edit by hand. -->

# 9takes Brand Kit

**Updated:** ${kit.BRAND_KIT_UPDATED}
**Live page:** https://9takes.com/admin/brand (admin only; same content plus a card studio)
**Source data:** \`src/lib/brand/brandKit.ts\`, \`brandTokens.ts\`, \`brandCardPresets.ts\`

Read this before writing copy, building a page, auditing messaging or making social assets.
Wording disputes: \`docs/brand/messaging-hierarchy.md\` wins. Visual disputes: \`docs/brand/cold-light.md\` wins.

## Hard rules for agents

- **Never generate images** (no OpenRouter, Gemini, Canva AI, OpenAI images, or driving ChatGPT). Render brand cards with \`pnpm brand:card\`, or write a statue prompt (below) and hand it to DJ.
- Never show what a take says before someone answers: not in previews, share cards, emails or posts.
- No amber, orange or warm light. Dark only.
- Anton lines are uppercase, 2 to 5 words, never a full sentence. Pair them with a Playfair italic quiet line.
- About one mint element per view: the action.

## Making assets

\`\`\`bash
pnpm brand:card -- --list                       # presets, templates, formats, statues
pnpm brand:card -- --preset ig-formula --out out.png
pnpm brand:card -- --template statement --format ig-post --kicker "Today's question" \\
  --headline "Answer before the crowd" --voice "Nine takes are waiting." --statue smirk --out card.png
pnpm brand:card -- --template question --format x-post --question "..." --out q.png
pnpm brand:card -- --template slide --format ig-post --index "03 / 07" --headline "..." --body "..." --out s3.png
pnpm brand:card -- --template person --name "Adam Sandler" --type 9 --portrait /types/9s/Adam-Sandler.webp --out p.png
pnpm gen:brand-og                               # re-render every site link preview after a copy change
\`\`\`

Templates: **statement** (loud + quiet line, statue or nine masks), **question** (question text, nine closed takes, mint action), **person** (portrait, name, type), **slide** (carousel body).

${table(
	['Format', 'Size', 'Use'],
	Object.entries(CARD_FORMATS).map(([id, f]) => [`\`${id}\``, `${f.width}×${f.height}`, f.label])
)}

### Presets

${table(
	['Preset', 'Format', 'Used on'],
	BRAND_CARD_PRESETS.map((p) => [
		`\`${p.id}\``,
		p.format,
		p.kind === 'og' ? `${p.usedOn} → ${ogImageUrl(p.id)}` : p.usedOn
	])
)}

## The message hierarchy (locked)

${table(
	['Level', 'Line', 'Job', 'Use in'],
	kit.HIERARCHY.map((h) => [h.level, `**${h.line}**`, h.job, h.useIn])
)}

**Main narrative:** ${kit.NARRATIVE}

**On-message test.** A reader can answer all four:

${kit.ACCEPTANCE_TEST.map((t, i) => `${i + 1}. ${t.q} ${t.a}`).join('\n')}

## Catchphrases in use

${table(
	['Line', 'Where'],
	kit.CATCHPHRASES.map((c) => [c.line, c.where])
)}

### Supporting vocabulary

${table(
	['Term', 'Note'],
	kit.VOCABULARY.map((v) => [v.term, v.note])
)}

### Retired lines (don't use)

${table(
	['Line', 'Why'],
	kit.RETIRED_LINES.map((r) => [`~~${r.line}~~`, r.why])
)}

## Voice

${table(
	['Trait', 'Means', 'Example'],
	kit.VOICE.map((v) => [v.trait, v.means, v.example])
)}

${bullets(kit.WRITING_RULES)}

## Logo

${table(
	['File', 'Size', 'Use'],
	kit.LOGOS.map((l) => [`\`static${l.file}\` (${l.label})`, l.size, l.use])
)}

${bullets(kit.LOGO_RULES)}

## Color

${table(
	['Name', 'Hex', 'Token', 'Use'],
	kit.PALETTE.map((c) => [c.name, `\`${c.hex}\``, `\`${c.token}\``, c.use])
)}

Statue tint ramp: ${kit.TINT_RAMP.map((s) => `${s.at} \`${s.hex}\` (${s.lands})`).join(' → ')}

## Type

${table(
	['Face', 'Token', 'Role', 'Rules'],
	kit.TYPEFACES.map((t) => [t.name, `\`${t.token}\``, t.role, t.rules])
)}

## Statues

${table(
	['Id', 'File', 'Statue', 'Emotion'],
	kit.STATUE_LIBRARY.map((s) => [`\`${s.id}\``, `\`static${s.file}\``, s.label, s.emotion])
)}

${bullets(kit.STATUE_RULES)}

**Prompt template for a new statue** (hand to DJ; he runs it in ChatGPT):

> ${kit.STATUE_PROMPT_TEMPLATE}

Then tint it: \`${kit.TINT_COMMAND}\` and add it to \`STATUES\` in \`src/lib/brand/brandTokens.ts\`.

## Accounts

${table(
	['Platform', 'Handle', 'Role'],
	kit.ACCOUNTS.map((a) => [a.platform, `[${a.handle}](${a.url})`, a.role])
)}

## Instagram

**Bio** (${kit.BIOS.instagram.status})

\`\`\`
${kit.BIOS.instagram.name}
${kit.BIOS.instagram.bio}
\`\`\`

${kit.BIOS.instagram.link}

${table(
	['What', 'Size', 'Note'],
	kit.INSTAGRAM.specs.map((s) => [s.what, s.size, s.note])
)}

${table(
	['Format', 'Detail'],
	kit.INSTAGRAM.formats.map((f) => [f.name, f.detail])
)}

${bullets(kit.INSTAGRAM.rules)}

Commands: ${kit.INSTAGRAM.commands.map((c) => `\`${c}\``).join(', ')}

## X

**Bio.** ${kit.BIOS.x.status}

- Live: ${kit.BIOS.x.live}
- Proposed: ${kit.BIOS.x.bio}

${table(
	['What', 'Size', 'Note'],
	kit.X.specs.map((s) => [s.what, s.size, s.note])
)}

Post formats: ${kit.X.formats.join(', ')}

${bullets(kit.X.rules)}

Commands: ${kit.X.commands.map((c) => `\`${c}\``).join(', ')}

## Tools

${table(
	['Tool', 'Where', 'Status', 'Note'],
	kit.TOOLS.map((t) => [t.name, `\`${t.where}\``, t.status, t.note])
)}

## Rules

**Always**

${bullets(kit.ALWAYS)}

**Never**

${bullets(kit.NEVER)}

## Open decisions (DJ)

${table(
	['Topic', 'Detail'],
	kit.OPEN_DECISIONS.map((d) => [d.topic, d.detail])
)}

## Sources

${kit.SOURCES.map((s) => `- \`${s.path}\`: ${s.what}`).join('\n')}
`;

await writeFile(OUT, doc);
console.log(`✓ ${path.relative(process.cwd(), OUT)}`);
